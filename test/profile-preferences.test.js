import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { startServer } from '../server/index.js';
import { TestClient } from './helpers/wsClient.js';
import { StubMatch } from '../server/match/StubMatch.js';
import { loadoutOptions } from '../shared/protocol.js';
import { diySlotIds, diyPool, diySlot } from '../shared/diy.js';
import { KITTED_CHARS } from '../server/sim/content/kits/index.js';
const voice = { voiceLanguage: 'cn', voiceOverrides: { char_102_texas: 'jp' } };
test('voice, skills/modules, ownership and DIY persist across devices/restart and isolate complete identities', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-profile-prefs-'));
  let server = await startServer({ host: '127.0.0.1', port: 0, quiet: true, profileDir: dir, MatchClass: StubMatch });
  const clients = [];
  const open = async (name) => { const c = await TestClient.connect(`ws://127.0.0.1:${server.port}/ws`); clients.push(c); const welcome = await c.hello(name); return { c, welcome }; };
  try {
    const { c: a, welcome: initial } = await open('配音博士#0001'); assert.equal(initial.profilePreferences.voiceLanguage, 'jp');
    const { c: b } = await open('配音博士#0001');
    assert.equal((await a.request({ t: 'profile.voice', preferences: voice })).t, 'ok');
    assert.deepEqual((await b.waitFor('profile.preferences')).preferences.voiceOverrides, voice.voiceOverrides);
    const data = server.lobby.safeData();
    const base = Object.values(data.chess).find((c) => !c.isGolden && !c.isDiy && c.visible !== false && !c.isHidden && loadoutOptions(c, data.chess[c.goldenId]).skills.length > 1);
    assert.ok(base);
    const opt = loadoutOptions(base, data.chess[base.goldenId]); const skill = opt.skills.find((n) => n !== opt.defaultSkill);
    const loadout = { [base.chessId]: { skill } };
    const ops = { [base.charId]: { potential: 2, cultivate: 1 } };
    assert.equal((await a.request({ t: 'room.loadout', entries: loadout, ops })).t, 'ok');
    const owned = Object.values(data.chess).find((c) => !c.isGolden && c.chessType === 'NORMAL');
    assert.equal((await a.request({ t: 'room.ownership', notOwned: [owned.chessId] })).t, 'ok');
    const slot = diySlotIds(data)[0], pool = diyPool(diySlot(slot, data).tier, { data, kitted: KITTED_CHARS });
    const picks = { [slot]: { charId: pool[0].charId || pool[0] } };
    assert.equal((await a.request({ t: 'room.diy', picks })).t, 'ok');
    const saved = server.lobby.profiles.read('配音博士', '0001');
    assert.equal(saved.preferences.loadout[base.chessId].skill, skill); assert.ok(Object.keys(saved.preferences.diy).length);
    assert.deepEqual(saved.preferences.ops, ops);
    const { welcome: other } = await open('配音博士#0002'); assert.equal(other.profilePreferences.voiceLanguage, 'jp'); assert.deepEqual(other.profilePreferences.loadout, {});
    assert.equal((await a.request({ t: 'profile.voice', preferences: { voiceLanguage: 'cn', voiceOverrides: { char_unknown: 'cn' } } })).code, 'BAD_MSG');
    assert.deepEqual(server.lobby.profiles.read('配音博士', '0001').preferences.voiceOverrides, voice.voiceOverrides);
    for (const c of clients) await c.close(); await server.close();
    server = await startServer({ host: '127.0.0.1', port: 0, quiet: true, profileDir: dir, MatchClass: StubMatch });
    const { c, welcome } = await open('配音博士#0001');
    assert.equal(welcome.profilePreferencesInitialized, true); assert.deepEqual(welcome.profilePreferences, saved.preferences);
    await c.request({ t: 'room.create', mode: 'coop', difficulty: 'NORMAL' });
    const session = server.registry.byId(welcome.playerId), seat = server.lobby.roomOf(session).seatOf(session.playerId);
    assert.deepEqual(seat.loadout, saved.preferences.loadout); assert.deepEqual(seat.diy, saved.preferences.diy);
    assert.deepEqual(seat.ops, ops);
    const before = session.preferences;
    const save = server.lobby.profiles.save; server.lobby.profiles.save = () => { throw new Error('disk unavailable'); };
    assert.equal((await c.request({ t: 'profile.voice', preferences: { voiceLanguage: 'jp', voiceOverrides: {} } })).code, 'INTERNAL');
    assert.deepEqual(session.preferences, before); server.lobby.profiles.save = save;
    await c.request({ t: 'room.addBot' }); await c.request({ t: 'room.start' });
    assert.equal((await c.request({ t: 'room.diy', picks: {} })).code, 'ROOM_STARTED');
    assert.deepEqual(server.lobby.profiles.read('配音博士', '0001').preferences.diy, {});
  } finally { await Promise.all(clients.map((c) => c.close())); await server.close(); fs.rmSync(dir, { recursive: true, force: true }); }
});
